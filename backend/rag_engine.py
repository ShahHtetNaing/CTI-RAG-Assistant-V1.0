def extract_email_urls(text):
    return re.findall(r"(?:https?://|www\.)[^\s<>\]\[()]+", text or "", flags=re.I)


def _normalise_domain(url):
    value = str(url).strip().rstrip(".,);]")
    if value.lower().startswith("www."):
        value = "http://" + value
    elif not re.match(r"^https?://", value, flags=re.I):
        value = "http://" + value
    try:
        host = (urlparse(value).hostname or "").lower().strip(".")
        return host[4:] if host.startswith("www.") else host
    except Exception:
        return ""


def check_email_domains(email_text):
    """Exact/suffix domain matching against the separately downloaded IOC set."""
    urls = extract_email_urls(email_text)
    results = []
    for url in urls:
        domain = _normalise_domain(url)
        if not domain:
            continue
        # Check the domain and each parent domain using set lookups (fast even for large feeds).
        matches = []
        candidate = domain
        while candidate:
            if candidate in IOC_DOMAINS:
                matches.append(candidate)
            if "." not in candidate:
                break
            candidate = candidate.split(".", 1)[1]
        results.append({"url": url, "domain": domain, "matches": matches[:5]})
    return results


