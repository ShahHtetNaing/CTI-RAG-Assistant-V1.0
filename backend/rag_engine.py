# Keyword index complements semantic retrieval for exact CVE IDs, malware names and techniques.
def tokenize_cti(text):
    return re.findall(r"(?u)[a-z0-9]+(?:[._-][a-z0-9]+)*", str(text).lower())

print("Building BM25 keyword index...")
bm25_corpus = [tokenize_cti(doc.page_content) for doc in docs]
