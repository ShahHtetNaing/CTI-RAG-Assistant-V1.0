def detect_email_indicators(email_text: str):
    """Transparent text indicators; not a probability or final phishing verdict."""
    text = email_text or ""
    lower = text.lower()
    findings = []

    if re.search(r"\b(urgent|immediately|act now|final warning|within\s+\d+\s+hours?)\b|account.{0,40}(suspend|disable|lock|terminate|expire)", lower, re.I):
        findings.append("Pressure or account-threat language is present.")
    if re.search(r"(enter|provide|confirm|verify|submit|update|reset|share).{0,70}(password|passcode|credentials|one[- ]?time code|MFA code|login details)|(password|passcode|credentials|one[- ]?time code|MFA code|login details).{0,70}(enter|provide|confirm|verify|submit|update|reset|share)", lower, re.I | re.S):
        findings.append("The message appears to request credentials or authentication information.")
    urls = extract_email_urls(text)
    if urls:
        findings.append(f"The message contains {len(urls)} visible URL(s).")
    if re.search(r"\b(wire transfer|bank account|payment details|gift card|change.{0,25}bank details)\b", lower, re.I):
        findings.append("The message requests or discusses a payment or banking action.")
    if re.search(r"\.(exe|scr|js|jse|vbs|vbe|hta|iso|img|lnk|bat|cmd|ps1|docm|xlsm)\b", lower, re.I):
        findings.append("A potentially executable or macro-enabled attachment is mentioned.")
    if re.search(r"password[- ]protected|enable macros|enable content|disable security|protected document", lower, re.I):
        findings.append("The message asks the recipient to bypass a security control or enable document content.")
    if not findings:
        findings.append("No matches were found by the built-in text checklist; this does not establish that the email is safe.")
    return findings


def classify_email_preliminary(email_text: str, findings):
    findings_text = " ".join(findings).lower()
    if "no matches were found" in findings_text:
        return "INSUFFICIENT EVIDENCE"
    credential = "request credentials" in findings_text
    payment = "payment or banking action" in findings_text
    pressure = "pressure or account-threat" in findings_text
    urls = "visible url" in findings_text
    attachment = "attachment is mentioned" in findings_text or "bypass a security control" in findings_text
    if (credential or payment) and (pressure or urls or attachment):
        return "POTENTIALLY SUSPICIOUS"
    if len(findings) >= 2:
        return "NEEDS FURTHER REVIEW"
    return "NEEDS FURTHER REVIEW"
