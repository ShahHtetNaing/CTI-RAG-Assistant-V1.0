def _query_terms(query, max_terms=8):
    terms = re.findall(r"[a-z0-9][a-z0-9._-]{2,}", str(query).lower())
    return [t for t in dict.fromkeys(terms) if t not in _STOP_WORDS][:max_terms]


def _rank_rows(frame, terms, max_rows=3):
    """Rank structured records with one vectorised text scan per query."""
    if frame.empty or not terms:
        return frame.iloc[0:0]

    clean_terms = list(dict.fromkeys(str(t).lower() for t in terms if len(str(t)) >= 3))
    if not clean_terms:
        return frame.iloc[0:0]

    # One combined regex is substantially cheaper than scanning the 60k-row
    # CVE frame once for every query term.
    alternatives = "|".join(re.escape(t) for t in sorted(clean_terms, key=len, reverse=True))
    pattern = rf"(?<![a-z0-9])(?:{alternatives})(?![a-z0-9])"
    matches = frame["_search_blob"].str.findall(pattern, flags=re.I)
    scores = matches.str.len().fillna(0).astype("int32")
    matched = frame.loc[scores > 0].copy()
    if matched.empty:
        return matched

    matched["_match_score"] = scores.loc[matched.index]
    sort_cols = ["_match_score"]
    ascending = [False]
    if "published_date" in matched.columns:
        sort_cols.append("published_date")
        ascending.append(False)
    elif "discovered" in matched.columns:
        sort_cols.append("discovered")
        ascending.append(False)
    return matched.sort_values(sort_cols, ascending=ascending).head(max_rows)


