def format_docs(retrieved_docs, max_chars_per_doc=700, label_prefix="S"):
    """Format evidence with stable labels and clear dataset provenance."""
    formatted = []
    for index, doc in enumerate(retrieved_docs, start=1):
        meta = doc.metadata or {}
        dataset_name = meta.get("source_dataset", "Unknown dataset")
        info = _dataset_info(dataset_name)
        label = f"{label_prefix}{index}"
        title = meta.get("title", "Untitled CTI record")
        record_type = meta.get("record_type", "CTI record")
        date = meta.get("record_date", "Date not supplied")
        record_id = meta.get("record_id", "Not supplied")
        source_url = meta.get("source_url", "")
        if source_url == info.get("url"):
            source_url = ""  # Do not mislabel a dataset-card URL as an original incident report.
        evidence = (doc.page_content or "")[:max_chars_per_doc]
        formatted.append(
            f"[{label}]\n"
            f"Title: {title}\n"
            f"Record type: {record_type}\n"
            f"Dataset: {dataset_name}\n"
            f"Dataset card: {info['url'] or 'Not supplied'}\n"
            f"Record date: {date}\n"
            f"Record ID: {record_id}\n"
            f"Original record/source URL: {source_url or 'Not supplied'}\n"
            f"Evidence: {evidence}"
        )
    return "\n\n".join(formatted)


