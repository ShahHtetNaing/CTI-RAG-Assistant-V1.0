def retrieve_incident_case_studies(query, max_cases=2):
    """Return up to two distinct named incident records relevant to broad sector/attack questions."""
    low = str(query).lower()
    active_sector_groups = [
        (name, pats) for name, pats in _CASE_SECTOR_PATTERNS.items()
        if any(re.search(pat, low, re.I) for pat in pats)
    ]
    active_attack_groups = [
        (name, pats) for name, pats in _CASE_ATTACK_PATTERNS.items()
        if any(re.search(pat, low, re.I) for pat in pats)
    ]
    # Keep this feature focused on requests that specify both a target sector and an attack type.
    if not active_sector_groups or not active_attack_groups or incident_df.empty:
        return []

    sector_patterns = [pat for _, pats in active_sector_groups for pat in pats]
    attack_patterns = [pat for _, pats in active_attack_groups for pat in pats]
    sector_regex = "(?:" + "|".join(sector_patterns) + ")"
    attack_regex = "(?:" + "|".join(attack_patterns) + ")"

    blobs = incident_df["_case_search_blob"].fillna("")
    sector_match = blobs.str.contains(sector_regex, regex=True, na=False)
    attack_match = blobs.str.contains(attack_regex, regex=True, na=False)
    candidates = incident_df.loc[sector_match & attack_match].copy()
    if candidates.empty:
        return []

    # Prefer records with more reporting outlets and higher publisher severity.
    # These are selection aids, not proof that one incident was more damaging.
    if "source_count" in candidates.columns:
        candidates["_source_rank"] = pd.to_numeric(candidates["source_count"], errors="coerce").fillna(0)
    else:
        candidates["_source_rank"] = 0
    if "severity_score" in candidates.columns:
        candidates["_severity_rank"] = pd.to_numeric(candidates["severity_score"], errors="coerce").fillna(0)
    else:
        candidates["_severity_rank"] = 0
    sort_cols = ["_source_rank", "_severity_rank"]
    ascending = [False, False]
    if "last_reported" in candidates.columns:
        sort_cols.append("last_reported")
        ascending.append(False)
    candidates = candidates.sort_values(sort_cols, ascending=ascending, kind="stable")

    case_docs = []
    seen = set()
    for _, row in candidates.iterrows():
        title = as_text(row.get("title"), 350) or "Untitled incident"
        cluster_id = as_text(row.get("cluster_id"), 100)
        dedupe_key = cluster_id or title.lower()
        if dedupe_key in seen:
            continue
        seen.add(dedupe_key)
        summary = as_text(row.get("summary"), 2200)
        entities = as_text(row.get("entities"), 1000)
        outlets = as_text(row.get("sources"), 900)
        first_reported = as_text(row.get("first_reported"), 50)
        last_reported = as_text(row.get("last_reported"), 50)
        source_url = as_text(row.get("url"), 600)
        content = (
            f"Named incident case: {title}\n"
            f"Summary: {summary}\n"
            f"Entities extracted by dataset publisher: {entities}\n"
            f"Reporting outlets: {outlets}\n"
            f"First reported: {first_reported}\n"
            f"Last reported: {last_reported}\n"
            "Evidence caveat: This is a generated incident-cluster summary. Verify key facts, impact and response in the linked reporting outlets. "
            "Do not infer financial loss or mitigation if not stated."
        )
        metadata = {
            "source_dataset": "threatcluster/threat-incident-clusters",
            "record_type": "incident_case_study",
            "title": title,
            "source_url": source_url,
            "record_date": last_reported or first_reported,
            "record_id": cluster_id,
        }
        case_docs.append(Document(page_content=content, metadata=metadata))
        if len(case_docs) >= max_cases:
            break
    return case_docs


