def query_response_style(query):
    low = str(query).lower()
    explicit_case_request = bool(re.search(
        r"\b(case studies?|documented cases?|real[- ]world examples?|examples of (?:attacks?|breaches?|incidents?)|give (?:me )?(?:one|two|three|some) (?:cases?|examples?|incidents?)|name (?:one|two|three) (?:attacks?|breaches?|incidents?))\b",
        low, re.I
    ))
    has_sector = any(re.search(pattern, low, re.I) for patterns in _CASE_SECTOR_PATTERNS.values() for pattern in patterns)
    has_attack = any(re.search(pattern, low, re.I) for patterns in _CASE_ATTACK_PATTERNS.values() for pattern in patterns)
    if explicit_case_request or (has_sector and has_attack):
        return "case_studies"
    asks_definition = bool(re.search(r"\b(what is|what are|define|definition of|explain|meaning of)\b", low, re.I))
    asks_mitigation = bool(re.search(r"\b(mitigat\w*|prevent\w*|protect\w*|defen[cs]\w*|countermeasure\w*)\b", low, re.I))
    if asks_definition and asks_mitigation:
        return "definition_mitigation"
    if asks_definition:
        return "definition"
    if asks_mitigation:
        return "mitigation"
    return "direct_answer"


def response_instruction_for(query):
    style = query_response_style(query)
    if style == "definition_mitigation":
        return (
            "QUESTION TYPE: Definition plus mitigation. Do NOT show documented cases, Case 1, or Case 2. "
            "Use this structure only: ## Direct answer (one or two sentences defining the concept from the records); "
            "## Mitigation documented in the selected datasets (bullet only actions explicitly present in records; otherwise write 'Not found in the selected datasets or live API results.'). "
            "Do not provide generic advice from model memory. Cite every fact with the exact [S#], [C#], [V#], [R#], or [L#] evidence label."
        )
    if style == "definition":
        return "QUESTION TYPE: Definition. Do NOT show cases. Give a direct, concise definition supported by records, cite each fact, and state missing details as 'Not found in the selected datasets or live API results.'"
    if style == "mitigation":
        return "QUESTION TYPE: Mitigation. Do NOT show cases unless explicitly requested. List only mitigations explicitly recorded in supplied data; otherwise say 'Not found in the selected datasets or live API results.' Cite each action."
    if style == "case_studies":
        return (
            "QUESTION TYPE: Case studies. Give up to TWO distinct named cases only if supplied case records exist. "
            "For each, cover what happened, target, impact/loss and documented response. No generic threat-group-only entries. "
            "For a missing field say 'Not found in the selected datasets or live API results.' Cite facts with [C#], [S#], or [L#]."
        )
    return "QUESTION TYPE: Direct CTI Q&A. Answer the exact question in a concise paragraph or bullets. Do NOT show cases unless requested. Cite every factual claim and mark missing facts as 'Not found in the selected datasets or live API results.'"


def has_relevant_selected_evidence(query, retrieved_docs, structured_context, case_docs=None, live_docs=None):
    usable_parts = [(doc.page_content or "").lower() for doc in (list(case_docs or []) + list(retrieved_docs or []) + list(live_docs or []))]
    if structured_context and structured_context.strip() not in {_NO_STRUCTURED, "Not applicable to this email-only check."}:
        usable_parts.append(str(structured_context).lower())
    evidence = "\n".join(usable_parts)
    if not evidence.strip():
        return False, []
    generic = set(_STOP_WORDS) | {
        "two", "three", "first", "second", "case", "cases", "example", "examples",
        "actual", "reported", "reporting", "known", "using", "dataset", "selected",
        "organisations", "organization", "organizations", "organisation", "please",
        "could", "would", "should", "state", "states", "regarding", "information"
    }
    anchors = [term for term in _query_terms(query, max_terms=20) if len(term) >= 4 and term not in generic]
    if not anchors:
        return False, []
    matched = [term for term in anchors if term in evidence]
    required = 1 if len(anchors) <= 2 else 2
    return len(matched) >= required, matched


